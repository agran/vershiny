/** Точка внутри полигона (правило чётности) */
function inPolygon(lon: number, lat: number, poly: [number, number][]): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

export function isInRussia(lon: number, lat: number): boolean {
  // Грубый отсев: Россия целиком в этих широтах
  if (lat < 40 || lat > 83) return false;
  const l = ((lon + 180) % 360 + 360) % 360 - 180; // нормализация к [-180, 180)
  return inPolygon(l, lat, RUSSIA) || inPolygon(l, lat, KALININGRAD);
}
