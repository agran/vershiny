/** Определение письменности строки */
export type Script =
  | 'latin'
  | 'cyrillic'
  | 'georgian'
  | 'armenian'
  | 'greek'
  | 'arabic'
  | 'tibetan'
  | 'devanagari'
  | 'thai'
  | 'ethiopic'
  | 'japanese'
  | 'korean'
  | 'chinese'
  | 'mixed';

export function detectScript(s: string): Script {
  const has = (re: RegExp) => re.test(s);
  const scripts: [Script, RegExp][] = [
    ['cyrillic', /[\u0400-\u04FF]/],
    ['georgian', /[\u10A0-\u10FF]/],
    ['armenian', /[\u0530-\u058F]/],
    ['greek', /[\u0370-\u03FF]/],
    ['arabic', /[\u0600-\u06FF]/],
    ['tibetan', /[\u0F00-\u0FFF]/],
    ['devanagari', /[\u0900-\u097F]/],
    ['thai', /[\u0E00-\u0E7F]/],
    ['ethiopic', /[\u1200-\u137F]/],
    ['japanese', /[\u30A0-\u30FF\u3040-\u309F]/],
    ['korean', /[\uAC00-\uD7AF\u1100-\u11FF]/],
    ['chinese', /[\u4E00-\u9FFF]/],
  ];
  const found = scripts.filter(([, re]) => has(re)).map(([s]) => s);
  if (found.length === 0) return 'latin';
  if (found.length === 1) return found[0];
  return 'mixed';
}

const MAPS: Partial<Record<Script, Record<string, string>>> = {
  cyrillic: RU_MAP,
  georgian: KA_MAP,
  armenian: HY_MAP,
  greek: EL_MAP,
  arabic: AR_MAP,
  tibetan: BO_MAP,
  devanagari: HI_MAP,
  thai: TH_MAP,
  ethiopic: AM_MAP,
  japanese: JA_MAP,
  korean: KO_MAP,
};

/** Транслитерация → латиница (любая письменность, включая смешанные строки) */
export function translitToLatin(s: string): string {
  const result = s
    .split('')
    .map((ch) => {
      const script = detectScript(ch);
      if (script === 'latin') return ch;
      const map = MAPS[script];
      if (!map) return ch; // chinese и прочие — оставляем как есть
      const lower = ch.toLowerCase();
      const tr = map[lower] ?? map[ch];
      if (tr === undefined) return ch;
      return ch === lower ? tr : tr.charAt(0).toUpperCase() + tr.slice(1);
    })
    .join('');
  // Капитализация первого символа после не-букв (начало строки, пробел, дефис)
  return result.replace(/(^|[\s\-–—(])(\w)/g, (_, sep: string, c: string) => sep + c.toUpperCase());
}

/** Транслитерация кириллицы → латиница (алиас для совместимости) */
export const translitToEn = translitToLatin;

/** Транслитерация латиницы → кириллица (грубая, только как fallback) */
export function translitToRu(s: string): string {
  let result = s.toLowerCase();
  for (const [en, ru] of EN_DIGRAPHS) {
    result = result.replaceAll(en, ru);
  }
  return result
    .split('')
    .map((ch) => EN_TO_RU[ch] ?? ch)
    .join('')
    .replace(/(^|\s)(.)/g, (_, sp: string, c: string) => sp + c.toUpperCase());
}

/** Есть ли кириллица в строке? */
export function isCyrillic(s: string): boolean {
  return /[\u0400-\u04FF]/.test(s);
}

/**
 * Читаемое название для локали:
 * - ru: кириллица как есть; латиница транслитерируется; прочее — как есть
 * - en: латиница как есть; всё прочее — транслитерация в латиницу
 */
export function readableName(name: string, locale: 'ru' | 'en'): string {
  if (locale === 'ru') {
    return isCyrillic(name) ? name : translitToRu(name);
  }
  return translitToLatin(name);
}
