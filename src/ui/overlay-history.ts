/**
 * Системный «назад» закрывает слой поверх панорамы, а не приложение.
 *
 * На телефоне жест «назад» — основной способ выйти из чего угодно. Пока
 * настройки и карта были просто элементами поверх холста, история браузера о
 * них не знала: жест уводил со страницы, то есть закрывал приложение целиком.
 * Человек, открывший настройки, чтобы сменить язык, вылетал из приложения.
 *
 * Приём стандартный для веб-приложений: на открытие слоя добавляется запись в
 * историю, и «назад» тратится на неё. Адрес при этом не меняется —
 * `pushState` без URL сохраняет текущий, поэтому ни ссылка, ни Service Worker
 * ничего не замечают.
 *
 * Слои держатся стопкой с одним общим слушателем. Слушатель на каждый слой не
 * годится: `popstate` получают все сразу, и один «назад» закрыл бы и поиск,
 * и карту под ним — а нажатие было одно.
 */

/** Метка наших записей: чужие (например, переход по ссылке) не трогаем */
const MARK = 'vershiny-overlay';

interface Overlay {
  id: number;
  onBack: () => void;
}

let counter = 0;
const stack: Overlay[] = [];
let listening = false;

function ensureListener(): void {
  if (listening) return;
  listening = true;
  window.addEventListener('popstate', () => {
    // Один шаг назад — один закрытый слой, верхний
    stack.pop()?.onBack();
  });
}

/**
 * Открыт слой: «назад» закроет его.
 *
 * @param onBack закрыть слой — вызывается, когда сработал системный «назад»
 * @returns снять слой с истории; вызывать, когда он закрылся сам (крестиком,
 *   Escape, кнопкой), чтобы «назад» не пришлось нажимать дважды
 */
export function pushOverlay(onBack: () => void): () => void {
  ensureListener();
  const id = ++counter;
  stack.push({ id, onBack });
  history.pushState({ [MARK]: id }, '');

  return () => {
    const index = stack.findIndex((overlay) => overlay.id === id);
    if (index === -1) return; // уже закрыт — хоть «назад», хоть повторно
    stack.splice(index, 1);
    // Наша запись всё ещё наверху — убираем её. Если сверху оказалось что-то
    // чужое, лучше оставить историю в покое: увести человека со страницы
    // хуже, чем оставить лишний шаг назад
    if ((history.state as Record<string, unknown> | null)?.[MARK] === id) {
      history.back();
    }
  };
}

/** Сброс стопки между тестами: в приложении она живёт до перезагрузки */
export function resetOverlayHistory(): void {
  stack.length = 0;
}
